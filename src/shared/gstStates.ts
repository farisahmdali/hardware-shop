export const GST_STATE_CODES = GST_STATES.map((s) => s.code);

/** GSTIN shape: 2-digit state code, 10-character PAN, entity number, 'Z', check character. */
export const GSTIN_PATTERN = /^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z][1-9A-Z]Z[0-9A-Z]$/;

const GSTIN_CHARS = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ';

/** Validates a GSTIN's shape and its mod-36 check character. */
export function isValidGstin(gstin: string): boolean {
  const value = gstin.toUpperCase();
  if (!GSTIN_PATTERN.test(value)) return false;
  let sum = 0;
  for (let i = 0; i < 14; i++) {
    const product = GSTIN_CHARS.indexOf(value[i]!) * (i % 2 === 0 ? 1 : 2);
    sum += Math.floor(product / 36) + (product % 36);
  }
  return GSTIN_CHARS[(36 - (sum % 36)) % 36] === value[14];
}

export function stateName(code: string | null | undefined): string {
  return GST_STATES.find((s) => s.code === code)?.name ?? '';
}
