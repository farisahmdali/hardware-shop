/**
 * Measures the operations a shop waits for, on a two-year dataset (30,000 products, ~100,000
 * bills, ~300,000 stock movements). Run with `npm run perf`; HWS_PERF_SIZE=small for a quick try.
 * The generated database is cached in node_modules/.cache so later runs skip the generation.
 */
const root = resolve(__dirname, '../..');
const sizes: PerfSizes = process.env.HWS_PERF_SIZE === 'small' ? { products: 2000, customers: 200, suppliers: 10, days: 30, invoicesPerDay: 137 } : FULL_SIZE;
const cacheDir = join(root, 'node_modules', '.cache', 'hws-perf');
const cached = join(cacheDir, `shop-v${LATEST_SCHEMA_VERSION}-${sizes.products}p-${sizes.days}d.db`);
const outDir = join(root, 'test-results');

let env: TestEnv;
let shop: ShopData;
let today: string;
const results: { group: string; name: string; n: number; p50: number; p95: number; max: number; limit?: number }[] = [];
const facts: Record<string, string | number> = {};

function measure(group: string, name: string, fn: () => unknown, n = 20, limit?: number) {
  fn(); // warm-up: the first run prepares statements and loads pages from disk
  const times: number[] = [];
  for (let i = 0; i < n; i++) {
    const t = performance.now();
    fn();
    times.push(performance.now() - t);
  }
  times.sort((a, b) => a - b);
  const at = (q: number) => Math.round(times[Math.min(times.length - 1, Math.floor(q * times.length))]! * 10) / 10;
  results.push({ group, name, n, p50: at(0.5), p95: at(0.95), max: at(1), limit });
}

async function measureAsync(group: string, name: string, fn: () => Promise<unknown>, n = 1) {
  const times: number[] = [];
  for (let i = 0; i < n; i++) {
    const t = performance.now();
    await fn();
    times.push(performance.now() - t);
  }
  const ms = Math.round(Math.max(...times));
  results.push({ group, name, n, p50: ms, p95: ms, max: ms });
}

beforeAll(() => {
  env = createTestEnv();
  env.db.close();
  for (const s of ['', '-wal', '-shm']) rmSync(env.paths.databasePath + s, { force: true });
  // A dataset generated by an earlier version is upgraded instead of generated again: this also
  // measures an upgrade of a large shop.
  const older = existsSync(cacheDir)
    ? readdirSync(cacheDir).filter((f) => f.endsWith(`-${sizes.products}p-${sizes.days}d.db`) && f !== basename(cached)).sort().pop()
    : undefined;
  if (!existsSync(cached) && older) {
    copyFileSync(join(cacheDir, older), env.paths.databasePath);
    env.db = openDatabase(env.paths.databasePath);
    const t = performance.now();
    const applied = migrate(env.db);
    facts['Upgrade of the generated shop'] = `${older.split('-')[1]} → v${LATEST_SCHEMA_VERSION} (migrations ${applied.join(', ')}) in ${Math.round(performance.now() - t)} ms`;
    env.db.pragma('wal_checkpoint(TRUNCATE)');
    env.db.close();
    copyFileSync(env.paths.databasePath, cached);
    rmSync(join(cacheDir, older), { force: true });
  }
  if (!existsSync(cached)) {
    const t = performance.now();
    env.db = openDatabase(env.paths.databasePath);
    // Generation runs on a freshly migrated file.
    migrate(env.db);
    seedPerfShop(env, sizes, (msg) => writeFileSync(join(outDir, 'perf-progress.txt'), `${new Date().toISOString()} ${msg}\n`, { flag: 'a' }));
    env.db.close();
    mkdirSync(cacheDir, { recursive: true });
    copyFileSync(env.paths.databasePath, cached);
    facts['Generation time'] = `${Math.round((performance.now() - t) / 1000)} s`;
  } else {
    copyFileSync(cached, env.paths.databasePath);
  }
  // The application's own connection settings (WAL, synchronous=FULL, foreign keys).
  env.db = openDatabase(env.paths.databasePath);
  const last = (env.db.prepare('SELECT MAX(issued_at) AS at FROM invoices').get() as { at: string }).at;
  env.clock.set(new Date(new Date(last).getTime() + 3_600_000).toISOString());
  shop = new ShopData(env, { userId: 1, username: 'owner' });
  today = shop.today();
}, 60 * 60_000);

afterAll(() => {
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, 'perf.json'), JSON.stringify({ facts, results }, null, 2));
  const lines = [
    '| Area | Operation | Runs | Median ms | 95th pct ms | Slowest ms | Limit ms |',
    '|---|---|---:|---:|---:|---:|---:|',
    ...results.map((r) => `| ${r.group} | ${r.name} | ${r.n} | ${r.p50} | ${r.p95} | ${r.max} | ${r.limit ?? ''} |`),
  ];
  writeFileSync(join(outDir, 'perf.md'), `${Object.entries(facts).map(([k, v]) => `- ${k}: ${v}`).join('\n')}\n\n${lines.join('\n')}\n`);
  env?.cleanup();
});

/** The registered customer with the most account entries (the walk-in customer is measured separately). */
const busiestCustomer = () =>
  (env.db.prepare("SELECT party_id AS id FROM ledger_entries WHERE party_type = 'CUSTOMER' AND party_id != ? GROUP BY party_id ORDER BY COUNT(*) DESC LIMIT 1").get(walkInCustomerId(env.db)) as { id: number }).id;

const count = (table: string) => (env.db.prepare(`SELECT COUNT(*) AS n FROM ${table}`).get() as { n: number }).n;

it('describes the dataset', () => {
  for (const t of ['products', 'customers', 'invoices', 'invoice_lines', 'stock_movements', 'payments', 'ledger_entries', 'audit_log', 'purchases', 'rental_agreements', 'credit_notes', 'expenses']) {
    facts[t] = count(t).toLocaleString('en-IN');
  }
  facts['Database size'] = `${Math.round(statSync(env.paths.databasePath).size / 1024 / 1024)} MB`;
  expect(count('products')).toBe(sizes.products);
});

it('searches and lists products and customers quickly', () => {
  const list = (f: Record<string, unknown>) => () =>
    listProducts(env.db, { stock: 'ALL', active: 'ACTIVE', sort: 'name', dir: 'asc', page: 1, pageSize: 50, ...f } as never, true);
  measure('Products', 'Search "hammer"', list({ search: 'hammer' }), 30, 50);
  measure('Products', 'Search "pvc pipe 20"', list({ search: 'pvc pipe 20' }), 30, 50);
  measure('Products', 'Search "bosch drill bit 8"', list({ search: 'bosch drill bit 8' }), 30, 50);
  measure('Products', 'Search by code "P-012345"', list({ search: 'P-012345' }), 30, 50);
  measure('Products', 'Search with no match', list({ search: 'zzqx' }), 30, 50);
  measure('Products', 'Full list, first page by name', list({}), 30, 100);
  measure('Products', 'Full list, page 300', list({ page: 300 }), 30, 100);
  measure('Products', 'Low or out of stock', list({ stock: 'LOW_OR_OUT' }), 20, 200);
  measure('Products', 'Sorted by stock value', list({ sort: 'value', dir: 'desc' }), 20, 200);
  const customers = (search?: string) => () => listCustomers(env.db, { search, filter: 'ALL', active: 'ACTIVE', includeWalkin: false, page: 1, pageSize: 50 }, today);
  measure('Customers', 'Search "Customer 1234"', customers('Customer 1234'), 30, 50);
  measure('Customers', 'Search a phone number', customers('9800001234'), 30, 50);
  measure('Customers', 'Who owes money', () => listCustomers(env.db, { filter: 'OWES', active: 'ACTIVE', includeWalkin: false, page: 1, pageSize: 50 }, today), 10, 500);
});

it('bills and takes payments quickly with the full, safe write settings', () => {
  const products = (env.db.prepare('SELECT id, selling_price AS sellingPrice, gst_rate_bp AS gstRateBp, price_includes_tax AS pit FROM products ORDER BY id LIMIT 300').all() as (PricedProduct & { pit: number })[]).map(
    (p) => ({ ...p, priceIncludesTax: p.pit === 1 }),
  );
  let i = 0;
  const walkIn = walkInCustomerId(env.db);
  measure('Billing', 'Finalize a 3-line counter sale', () => {
    const lines = [0, 1, 2].map((k) => ({ p: products[(i * 3 + k) % products.length]!, qty: units(1) }));
    i++;
    shop.sell(walkIn, lines, 'all');
  }, 50, 100);
  const customer = (env.db.prepare("SELECT id FROM customers WHERE is_walkin = 0 ORDER BY id LIMIT 1").get() as { id: number }).id;
  measure('Billing', 'Finalize a credit sale', () => shop.sell(customer, [{ p: products[i++ % products.length]!, qty: units(2) }], 'none'), 30, 100);
  measure('Billing', 'Receive a payment (settles oldest bills)', () => shop.receive(customer, rupees(100)), 30, 100);
  const invoiceId = (env.db.prepare('SELECT MAX(id) AS id FROM invoices').get() as { id: number }).id;
  measure('Billing', 'Open an invoice', () => getInvoice(env.db, invoiceId, true, today), 30, 50);
  const busiest = busiestCustomer();
  measure('Customers', 'Open the busiest account customer', () => getCustomer(env.db, busiest, today), 20, 100);
  measure('Customers', 'Busiest account customer ledger, all time', () => customerLedger(env.db, busiest, {}, today), 10, 500);
  measure('Customers', 'Open the walk-in customer', () => getCustomer(env.db, walkIn, today), 10, 100);
});

it('loads the dashboard and history quickly', () => {
  const month = today.slice(0, 8) + '01';
  measure('Dashboard', 'Today', () => dashboardPeriod(env.db, today, today, ALL_PERMISSIONS), 20, 300);
  measure('Dashboard', 'This month', () => dashboardPeriod(env.db, month, today, ALL_PERMISSIONS), 10, 500);
  measure('Dashboard', 'Last 12 months', () => dashboardPeriod(env.db, addDays(today, -364), today, ALL_PERMISSIONS), 5, 2000);
  measure('Dashboard', 'Recent transactions and changes', () => dashboardRecent(env.db, ALL_PERMISSIONS), 20, 200);
  measure('History', 'Newest entries', () => listAudit(env.db, { page: 1, pageSize: 50 }), 20, 100);
  measure('History', 'Search "hammer"', () => listAudit(env.db, { page: 1, pageSize: 50, search: 'hammer' }), 5, 1500);
  // Text searches read every history entry (a quarter of a million here); not a counter operation.
  measure('History', 'Search a bill number', () => listAudit(env.db, { page: 1, pageSize: 50, search: 'INV/2025-26/00100' }), 10, 1500);
  const customer = (env.db.prepare("SELECT id FROM customers WHERE is_walkin = 0 ORDER BY id LIMIT 1").get() as { id: number }).id;
  measure('History', 'One customer and linked records', () => listAudit(env.db, { page: 1, pageSize: 25, record: { type: 'customer', id: String(customer) } }), 20, 200);
});

it('produces every report for a year (in the background worker in the app)', () => {
  const customer = busiestCustomer();
  const supplier = (env.db.prepare('SELECT supplier_id AS id FROM purchases GROUP BY supplier_id ORDER BY COUNT(*) DESC LIMIT 1').get() as { id: number }).id;
  const params = { from: addDays(today, -364), to: today };
  for (const def of REPORTS) {
    measure(
      'Reports (12 months)',
      def.title,
      () =>
        runReport(env.db, def.id, { ...params, customerId: def.requires === 'customer' ? customer : undefined, supplierId: def.requires === 'supplier' ? supplier : undefined }, {
          today,
          nowIso: env.clock.now().toISOString(),
          permissions: ALL_PERMISSIONS,
        }),
      2,
      10_000,
    );
  }
  measure('Reports (12 months)', 'Statement of the walk-in customer, one month', () =>
    runReport(env.db, 'parties.customerStatement', { from: addDays(today, -30), to: today, customerId: walkInCustomerId(env.db) }, { today, nowIso: env.clock.now().toISOString(), permissions: ALL_PERMISSIONS }),
    2, 10_000);
});

it('starts, checks and backs up in reasonable time', async () => {
  measure('Start-up', 'Open the database and check its version', () => {
    const db = openDatabase(env.paths.databasePath);
    pendingMigrations(db);
    buildSession(db, 1);
    db.close();
  }, 5, 1000);
  // Both run in the background worker in the application, so the window stays responsive.
  measure('Background', 'Quick data check (after every start)', () => runIntegrityChecks(env.db, { quickOnly: true }), 3);
  measure('Background', 'Full data check (Data health)', () => runIntegrityChecks(env.db), 1);
  const full = runIntegrityChecks(env.db);
  facts['Full data check problems'] = full.issues.length;
  expect(full.issues).toEqual([]);
  await measureAsync('Background', 'Verified backup of the whole database', () => createBackup(env, shop.actor, 'MANUAL'));
});

it('meets every time limit', () => {
  const slow = results.filter((r) => r.limit !== undefined && r.p95 > r.limit).map((r) => `${r.group} / ${r.name}: ${r.p95} ms (limit ${r.limit})`);
  expect(slow).toEqual([]);
});
